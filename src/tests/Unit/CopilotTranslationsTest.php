<?php

declare(strict_types=1);

namespace CentralVet\Tests\Unit;

use CentralVet\Tests\Support\Assert;

/**
 * Fase 8B, T-07: contrato de textos pt/en das telas do copiloto
 * (T-14, T-15, T-16, T-23) em translations.json.
 */
final class CopilotTranslationsTest
{
    private const KEYS = [
        'Copilot' => 'Copiloto',
        'Clinical copilot' => 'Copiloto clínico',
        'Management copilot' => 'Copiloto de gestão',
        'Ask the copilot' => 'Pergunte ao copiloto',
        'Your question' => 'Sua pergunta',
        'Thinking…' => 'Pensando…',
        'New conversation' => 'Nova conversa',
        'Delete conversation' => 'Apagar conversa',
        'Conversation deleted' => 'Conversa apagada',
        'Conversation not found' => 'Conversa não encontrada',
        'My conversations' => 'Minhas conversas',
        'Previous conversations' => 'Conversas anteriores',
        'Consulted' => 'Consultei',
        'The answer failed; you can send the question again' => 'A resposta falhou; você pode reenviar a pergunta',
        'Answer generated by AI from system data. Check before using.' => 'Resposta gerada por IA a partir dos dados do sistema. Confira antes de usar.',
        'Tool audit' => 'Auditoria de ferramentas',
        'Tool' => 'Ferramenta',
        'Decision' => 'Decisão',
        'Allowed' => 'Permitida',
        'Denied' => 'Negada',
        'Rows' => 'Linhas',
        'Truncated' => 'Truncado',
        'Duration (ms)' => 'Duração (ms)',
        'Family' => 'Família',
        'Clinical' => 'Clínica',
        'Management' => 'Gestão',
        'Answered' => 'Respondida',
        'Patient not found' => 'Paciente não encontrado',
        'Correlation id' => 'Id de correlação',
        'Filter' => 'Filtrar',
        'No conversations yet' => 'Nenhuma conversa ainda',
        'No tool calls in the period' => 'Nenhuma chamada de ferramenta no período',
    ];

    public function testEveryCopilotKeyHasTheExactPortugueseText(): void
    {
        $translations = [];
        foreach (self::entries() as $entry) {
            $translations[$entry['en']] = $entry['pt'];
        }

        foreach (self::KEYS as $en => $pt) {
            Assert::true(isset($translations[$en]), "Missing translation for copilot key: {$en}");
            Assert::same($pt, $translations[$en], "Wrong pt for copilot key: {$en}");
        }
    }

    public function testListIsSortedByEnglishKeyCaseInsensitive(): void
    {
        $entries = self::entries();
        for ($i = 1, $n = count($entries); $i < $n; $i++) {
            $previous = $entries[$i - 1]['en'];
            $current = $entries[$i]['en'];
            Assert::true(strcasecmp($previous, $current) <= 0, "translations.json out of order at {$i}: \"{$previous}\" before \"{$current}\"");
        }
    }

    public function testEnglishKeysAreUnique(): void
    {
        $seen = [];
        foreach (self::entries() as $entry) {
            Assert::true(!isset($seen[$entry['en']]), "Duplicate translation key: {$entry['en']}");
            $seen[$entry['en']] = true;
        }
    }

    public function testEveryEntryHasExactlyNonEmptyEnAndPt(): void
    {
        $violations = self::shapeViolations(self::entries());

        Assert::same([], $violations, 'translations.json entries must have exactly en and pt, both non-empty strings');
    }

    /**
     * ApplicationTranslator indexa pt/en por posição: uma entrada fora da forma
     * {en, pt} desalinha todas as seguintes.
     *
     * @param array<mixed> $entries
     * @return list<string>
     */
    public static function shapeViolations(array $entries): array
    {
        $violations = [];
        foreach ($entries as $index => $entry) {
            if (!is_array($entry)) {
                $violations[] = "{$index}: not an object";
                continue;
            }
            $keys = array_keys($entry);
            sort($keys);
            if ($keys !== ['en', 'pt']) {
                $violations[] = "{$index}: keys " . implode(',', $keys);
                continue;
            }
            foreach (['en', 'pt'] as $lang) {
                if (!is_string($entry[$lang]) || trim($entry[$lang]) === '') {
                    $violations[] = "{$index}: empty or non-string {$lang}";
                }
            }
        }

        return $violations;
    }

    /**
     * @return list<array{en: string, pt: string}>
     */
    private static function entries(): array
    {
        $decoded = json_decode((string) file_get_contents(dirname(__DIR__, 2) . '/app/config/translations.json'), true);
        Assert::true(is_array($decoded), 'translations.json must decode to a list');

        return $decoded;
    }
}
