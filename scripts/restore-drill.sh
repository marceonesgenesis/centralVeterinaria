#!/usr/bin/env bash
# Restore drill in an isolated Compose project (T-11).
#
# Usage: scripts/restore-drill.sh [--keep] <file>
#
# Brings up mysql, redis, app and worker of the project centralvet-drill (own volumes and
# env-file var/drill/.env, generated once with random secrets, HTTP_PORT=18081),
# restores <file> there with scripts/restore.sh, compares the MANIFEST counts
# with what was restored and, unless --keep, removes the project with
# `down -v` (plus any leftover centralvet-drill_* volume). It never addresses
# any other project.
#
# <file> is a centralvet-*.tar.gpg or centralvet-*.tar.gz.cvbk inside
# $BACKUP_DIR (BACKUP_DIR and BACKUP_PASSPHRASE_FILE come from the
# environment, as for restore.sh). RESTORE_DRILL_ENV_FILE overrides the
# env-file path (default var/drill/.env).
#
# Output: `restore-drill verify <item> manifest=<n> restored=<n>` for
# table_count, each `rows <table>`, files_count, documents_count and
# migrations, `restore-drill verify services_running manifest=<n> restored=<n>`
# (app/worker running before and after the restore, which stops and restarts
# them: T-18) and `restore-drill verify maintenance_flag manifest=0
# restored=<0|1>` (var/maintenance/centralvet-drill.restore left behind),
# then `restore-drill done elapsed_seconds=<n> decrypt_seconds=<n>
# db_seconds=<n> files_seconds=<n> mismatches=<n>`.
# Exit codes: 0 no mismatch; 1 mismatches; 2 usage or configuration;
# 4 the drill project did not start; otherwise restore.sh's exit code.
set -uo pipefail

project_root=$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
project=centralvet-drill

usage() {
    echo 'Usage: scripts/restore-drill.sh [--keep] <file>' >&2
}

keep=0
input=''
while [ "$#" -gt 0 ]; do
    case "$1" in
        --keep) keep=1; shift ;;
        -h|--help) usage; exit 0 ;;
        -*) usage; exit 2 ;;
        *) [ -z "$input" ] || { usage; exit 2; }; input=$1; shift ;;
    esac
done
[ -n "$input" ] || { usage; exit 2; }
case "$input" in
    *.tar.gpg|*.tar.gz.cvbk) ;;
    *) echo 'restore-drill: only .tar.gpg or .tar.gz.cvbk backups carry a MANIFEST to verify' >&2; exit 2 ;;
esac
command -v openssl >/dev/null 2>&1 || { echo 'restore-drill: openssl is required' >&2; exit 2; }

env_file=${RESTORE_DRILL_ENV_FILE:-$project_root/var/drill/.env}
case "$env_file" in /*) ;; *) env_file="$(pwd)/$env_file" ;; esac

started=$SECONDS
umask 077
if [ ! -f "$env_file" ]; then
    mkdir -p "$(dirname "$env_file")" || exit 2
    {
        echo "# Generated by scripts/restore-drill.sh for the isolated project $project."
        echo "COMPOSE_PROJECT_NAME=$project"
        echo 'HTTP_PORT=18081'
        echo 'MINIO_PORT=19000'
        echo 'MINIO_CONSOLE_PORT=19001'
        echo 'APP_ENV=development'
        echo "APP_SEED=$(openssl rand -hex 32)"
        echo 'MYSQL_DATABASE=centralvet'
        echo 'MYSQL_USER=centralvet'
        echo "MYSQL_PASSWORD=$(openssl rand -hex 24)"
        echo "MYSQL_ROOT_PASSWORD=$(openssl rand -hex 24)"
    } > "$env_file" || { echo "restore-drill: cannot write $env_file" >&2; exit 2; }
    chmod 600 "$env_file"
fi
grep -qx "COMPOSE_PROJECT_NAME=$project" "$env_file" \
    || { echo "restore-drill: $env_file does not set COMPOSE_PROJECT_NAME=$project" >&2; exit 2; }

compose() {
    docker compose -p "$project" --env-file "$env_file" "$@"
}

teardown() {
    [ "$keep" -eq 1 ] && return 0
    compose down -v --remove-orphans >/dev/null 2>&1 || echo "restore-drill: down -v of $project failed" >&2
    # Volumes created outside Compose (e.g. <project>_minio_data by restore.sh).
    local volume
    while IFS= read -r volume; do
        case "$volume" in "${project}_"*) docker volume rm "$volume" >/dev/null 2>&1 ;; esac
    done < <(docker volume ls -q --filter "name=${project}_" 2>/dev/null)
}

work=$(mktemp -d "${TMPDIR:-/tmp}/centralvet-restore-drill.XXXXXX") || exit 2
finish() {
    local code=$?
    teardown
    rm -rf "$work"
    exit "$code"
}
trap finish EXIT
trap 'exit 4' HUP INT TERM

compose up -d --wait mysql redis app worker >/dev/null || { echo "restore-drill: $project did not start" >&2; exit 4; }

# running_writers: how many of app/worker are running.
running_writers() {
    compose ps --services --status running </dev/null 2>/dev/null | grep -cxE 'app|worker'
}
writers_before=$(running_writers)

RESTORE_MANIFEST_COPY="$work/MANIFEST" CONFIRM_RESTORE=RESTORE_CENTRALVET_DRILL \
    bash "$project_root/scripts/restore.sh" --project "$project" --env-file "$env_file" "$input" > "$work/restore.out"
restore_status=$?
cat "$work/restore.out"
[ "$restore_status" -eq 0 ] || exit "$restore_status"
[ -f "$work/MANIFEST" ] || { echo 'restore-drill: restore.sh did not hand over the MANIFEST' >&2; exit 2; }

timing() {
    grep -o "$1=[0-9]*" "$work/restore.out" | tail -n 1 | cut -d= -f2
}
decrypt_seconds=$(timing decrypt_seconds)
db_seconds=$(timing db_seconds)
files_seconds=$(timing files_seconds)

# --- restored counts ------------------------------------------------------
{
    echo '-- restore-drill-verify'
    echo "SELECT CONCAT('table_count=', COUNT(*)) FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE = 'BASE TABLE';"
    sed -n 's/^rows \([A-Za-z0-9_]*\)=[0-9]*$/\1/p' "$work/MANIFEST" | while IFS= read -r table; do
        echo "SELECT CONCAT('rows $table=', COUNT(*)) FROM \`$table\`;"
    done
    echo "SELECT CONCAT('migrations=', COUNT(*)) FROM schema_migrations;"
} > "$work/verify.sql"
compose exec -T mysql sh -ceu \
    'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" exec mysql -uroot --batch --skip-column-names --force "$MYSQL_DATABASE"' \
    < "$work/verify.sql" > "$work/restored" 2>"$work/verify.err" || true
compose run --rm --no-deps -T --entrypoint sh app -ceu \
    ': restore-drill-count
printf "files_count=%s\n" "$(find /var/www/html/src/files -mindepth 1 ! -type d | wc -l)"
printf "documents_count=%s\n" "$(find /var/www/html/var/documents -mindepth 1 ! -type d | wc -l)"' \
    </dev/null >> "$work/restored" 2>>"$work/verify.err" || true

restored_value() {
    local value
    value=$(grep -F "$1=" "$work/restored" | grep -E "^$1=" | tail -n 1 | cut -d= -f2 | tr -d '[:space:]')
    printf '%s' "${value:-missing}"
}

mismatches=0
verify() {
    local item=$1 expected=$2 actual=$3
    echo "restore-drill verify $item manifest=$expected restored=$actual"
    [ "$expected" = "$actual" ] || mismatches=$((mismatches + 1))
}

manifest_value() {
    local value
    value=$(grep -E "^$1=" "$work/MANIFEST" | tail -n 1 | cut -d= -f2)
    printf '%s' "${value:-missing}"
}

verify table_count "$(manifest_value table_count)" "$(restored_value table_count)"
while IFS='=' read -r key expected; do
    verify "$key" "$expected" "$(restored_value "$key")"
done < <(grep -E '^rows [A-Za-z0-9_]+=[0-9]+$' "$work/MANIFEST")
verify files_count "$(manifest_value files_count)" "$(restored_value files_count)"
verify documents_count "$(manifest_value documents_count)" "$(restored_value documents_count)"
verify migrations "$(grep -c '^migration ' "$work/MANIFEST")" "$(restored_value migrations)"
verify services_running "$writers_before" "$(running_writers)"
flag_left=0
[ -e "${CENTRALVET_MAINTENANCE_DIR:-$project_root/var/maintenance}/$project.restore" ] && flag_left=1
verify maintenance_flag 0 "$flag_left"
[ "$mismatches" -eq 0 ] || sed 's/^/restore-drill: /' "$work/verify.err" >&2

echo "restore-drill done elapsed_seconds=$((SECONDS - started)) decrypt_seconds=${decrypt_seconds:-0} db_seconds=${db_seconds:-0} files_seconds=${files_seconds:-0} mismatches=$mismatches"
[ "$mismatches" -eq 0 ] || exit 1
exit 0
